"""
Modern Analytics Transformation Runner using dbt Core (Milestone V2.4)
Wraps dbt Core CLI operations (compile, run, test) and inspects compilation
DAG artifacts (manifest.json, run_results.json) for lineage and test reporting.
"""

import json
import os
import shutil
import subprocess
import sys
import time
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any


@dataclass
class DbtExecutionResult:
    command: str
    success: bool
    returncode: int
    stdout: str
    stderr: str
    elapsed_seconds: float
    results: list[dict[str, Any]] = field(default_factory=list)


class DbtRunner:
    """
    Programmatic interface for managing and invoking the dbt Core project in analytics_dbt/.
    """

    def __init__(
        self,
        project_dir: Path | str | None = None,
        profiles_dir: Path | str | None = None,
    ):
        base_dir = Path(__file__).resolve().parent.parent.parent
        self.project_dir = (
            Path(project_dir) if project_dir else (base_dir / "analytics_dbt")
        )
        self.profiles_dir = Path(profiles_dir) if profiles_dir else self.project_dir

        if not self.project_dir.exists():
            raise FileNotFoundError(
                f"dbt project directory not found: {self.project_dir}"
            )

    def _find_dbt_executable(self) -> list[str]:
        """Resolves the dbt executable from virtual environment or PATH."""
        # 1. Virtual environment dbt
        venv_scripts = Path(sys.executable).parent
        dbt_venv = venv_scripts / ("dbt.exe" if os.name == "nt" else "dbt")
        if dbt_venv.exists():
            return [str(dbt_venv)]

        # 2. System PATH
        which_dbt = shutil.which("dbt")
        if which_dbt:
            return [which_dbt]

        # 3. Python module invocation
        return [sys.executable, "-m", "dbt.cli.main"]

    def execute(
        self,
        args: list[str],
        env: dict[str, str] | None = None,
        timeout: int = 120,
    ) -> DbtExecutionResult:
        """
        Executes a dbt command with project and profile directory flags.
        """
        cmd = self._find_dbt_executable() + args
        cmd += ["--project-dir", str(self.project_dir)]
        cmd += ["--profiles-dir", str(self.profiles_dir)]

        run_env = os.environ.copy()
        if env:
            run_env.update(env)

        start_time = time.perf_counter()
        proc = subprocess.run(
            cmd,
            capture_output=True,
            check=False,
            text=True,
            encoding="utf-8",
            env=run_env,
            timeout=timeout,
        )
        elapsed = time.perf_counter() - start_time

        parsed_results = self._load_run_results()

        return DbtExecutionResult(
            command=" ".join(cmd),
            success=(proc.returncode == 0),
            returncode=proc.returncode,
            stdout=proc.stdout,
            stderr=proc.stderr,
            elapsed_seconds=elapsed,
            results=parsed_results,
        )

    def _load_run_results(self) -> list[dict[str, Any]]:
        """Parses target/run_results.json if generated by the command."""
        run_results_path = self.project_dir / "target" / "run_results.json"
        if run_results_path.exists():
            try:
                data = json.loads(run_results_path.read_text(encoding="utf-8"))
                return data.get("results", [])
            except (json.JSONDecodeError, OSError):
                return []
        return []

    def load_manifest(self) -> dict[str, Any]:
        """Loads and returns target/manifest.json compiled graph metadata."""
        manifest_path = self.project_dir / "target" / "manifest.json"
        if not manifest_path.exists():
            # Trigger compile if manifest does not exist
            compile_res = self.compile()
            if not compile_res.success:
                raise RuntimeError(
                    f"dbt compilation failed:\n{compile_res.stderr or compile_res.stdout}"
                )

        return json.loads(manifest_path.read_text(encoding="utf-8"))

    def compile(self, select: str | None = None) -> DbtExecutionResult:
        """Compiles models and generates DAG manifest."""
        args = ["compile"]
        if select:
            args += ["--select", select]
        return self.execute(args)

    def run(
        self, select: str | None = None, full_refresh: bool = False
    ) -> DbtExecutionResult:
        """Executes dbt run."""
        args = ["run"]
        if select:
            args += ["--select", select]
        if full_refresh:
            args.append("--full-refresh")
        return self.execute(args)

    def test(self, select: str | None = None) -> DbtExecutionResult:
        """Executes dbt test."""
        args = ["test"]
        if select:
            args += ["--select", select]
        return self.execute(args)

    def list_models(self) -> list[str]:
        """Lists all model names declared in the dbt project."""
        manifest = self.load_manifest()
        nodes = manifest.get("nodes", {})
        models = [
            node["name"]
            for node in nodes.values()
            if node.get("resource_type") == "model"
        ]
        return sorted(models)

    def get_model_dependencies(self, model_name: str) -> list[str]:
        """Returns upstream model names that the given model depends on."""
        manifest = self.load_manifest()
        nodes = manifest.get("nodes", {})
        for node in nodes.values():
            if node.get("resource_type") == "model" and node.get("name") == model_name:
                depends = node.get("depends_on", {}).get("nodes", [])
                return sorted(
                    [d.split(".")[-1] for d in depends if d.startswith("model.")]
                )
        return []
