"""Schemas for AI-Assisted ERP (Roadmap §V1.7)"""

from typing import Any, Literal

from pydantic import BaseModel, Field

DraftActionType = Literal[
    "create_activity",
    "create_quote",
    "update_lead_status",
    "create_opportunity",
    "send_email",
    "update_opportunity_stage",
]


class DraftAction(BaseModel):
    """
    Structured action draft generated by the AI assistant.
    Strict Invariant: confirmation_required is ALWAYS True; the AI assistant
    NEVER commits any database modification directly.
    """

    action_type: DraftActionType
    title: str
    description: str
    confirmation_required: bool = True
    payload: dict[str, Any]
    preview_data: dict[str, Any] | None = None
    explanation: str | None = None


class AssistantChatRequest(BaseModel):
    """Incoming user prompt with optional record context."""

    message: str = Field(..., min_length=1, max_length=2000)
    entity_type: str | None = None  # e.g., 'lead', 'customer', 'opportunity', 'invoice'
    entity_id: int | None = None
    session_id: str | None = None


class AssistantChatResponse(BaseModel):
    """Response returned to user with executive narrative and draft actions."""

    reply: str
    draft_action: DraftAction | None = None
    tool_calls: list[str] = Field(default_factory=list)
    entity_context: dict[str, Any] | None = None
    refused: bool = False
    refusal_reason: str | None = None


class LeadSummaryResponse(BaseModel):
    lead_id: int
    lead_no: str
    name: str
    company_name: str | None = None
    status: str
    owner_id: int | None = None
    summary: str
    key_highlights: list[str] = Field(default_factory=list)
    suggested_next_action: str | None = None
    activity_count: int = 0


class CustomerSummaryResponse(BaseModel):
    customer_id: int
    customer_no: str
    name: str
    status: str
    summary: str
    open_opportunities_count: int = 0
    total_opportunities_value: str = "0.00"
    recent_activities: list[dict[str, Any]] = Field(default_factory=list)
    financial_overview: dict[str, Any] = Field(default_factory=dict)


class OpportunityNextStepsResponse(BaseModel):
    opportunity_id: int
    opportunity_no: str
    name: str
    stage: str
    estimated_amount: str
    probability: str
    summary: str
    recommended_steps: list[str] = Field(default_factory=list)
    draft_action: DraftAction | None = None


class DraftEmailRequest(BaseModel):
    entity_type: Literal["lead", "customer", "opportunity"]
    entity_id: int
    purpose: str | None = "follow_up"
    user_instructions: str | None = None


class DraftEmailResponse(BaseModel):
    recipient_email: str | None = None
    recipient_name: str | None = None
    subject: str
    body: str
    draft_action: DraftAction


class ExplainInvoiceResponse(BaseModel):
    invoice_id: int
    invoice_no: str
    customer_name: str
    status: str
    due_date: str | None = None
    is_overdue: bool = False
    grand_total: str
    amount_paid: str
    amount_credited: str
    balance_due: str
    narrative: str
    line_items: list[dict[str, Any]] = Field(default_factory=list)
    payments_applied: list[dict[str, Any]] = Field(default_factory=list)
    credits_applied: list[dict[str, Any]] = Field(default_factory=list)


class RecordSearchResponse(BaseModel):
    query: str
    total_found: int
    results: list[dict[str, Any]] = Field(default_factory=list)
